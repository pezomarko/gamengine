pub fn packet(amount: u16, dtype: DamageType, knockback: f32, stagger: u8) -> DamagePacket {
    DamagePacket {
        amount,
        dtype,
        bypass: Bypass::NONE,
        knockback,
        stagger,
    }
}

pub fn status(
    status: Status,
    ms: u32,
    magnitude: f32,
    stacking: StackRule,
    max_stacks: u8,
    target: StatusTarget,
    rate: TickRate,
) -> ApplyStatus {
    ApplyStatus {
        status,
        duration: rate.ms_to_ticks(ms),
        magnitude,
        max_stacks,
        stacking,
        target,
        dispellable: true,
    }
}

#[allow(clippy::too_many_arguments)]
fn melee(
    rate: TickRate,
    reach: f32,
    arc_deg: f32,
    windup_ms: u32,
    active_ms: u32,
    recovery_ms: u32,
    damage: DamagePacket,
    max_targets: u8,
    cleave: f32,
) -> Verb {
    Verb::MeleeArc(MeleeArc {
        reach,
        arc_deg,
        half_height: 40.0,
        timing: Timing {
            windup: rate.ms_to_ticks(windup_ms),
            active: rate.ms_to_ticks(active_ms),
            recovery: rate.ms_to_ticks(recovery_ms),
        },
        damage,
        max_targets,
        cleave_falloff: cleave,
        parryable: true,
        hit_stop: rate.ms_to_ticks(30),
        assist_deg: 0.0,
    })
}

/// An arc with the magnet (MODES.md 4.2).
fn assisted(verb: Verb, deg: f32) -> Verb {
    match verb {
        Verb::MeleeArc(m) => Verb::MeleeArc(MeleeArc {
            assist_deg: deg,
            ..m
        }),
        v => v,
    }
}

/// A bullet (MODES.md 3.6): 20,000 u/s, flat, gone within 400 ms, no spread of its own.
fn bullet(rate: TickRate, damage: DamagePacket, offset: [f32; 3]) -> Verb {
    Verb::Projectile(Projectile {
        speed: 20000.0,
        gravity_scale: 0.02,
        radius: 2.0,
        lifetime: rate.ms_to_ticks(400),
        damage,
        pierce: 0,
        bounce: Bounce::default(),
        drag: 0.0,
        spawn: Origin::Weapon { offset },
        inherit_velocity: 0.0,
        spread_deg: 0.0,
        count: 1,
        // Tagging (MODES.md 10.2): a body hit by a bullet is slowed for a moment.
        on_hit: vec![Trigger::Status(status(
            Status::Slow,
            1500,
            0.5,
            StackRule::Refresh,
            1,
            StatusTarget::Hit,
            rate,
        ))],
        on_expire: vec![],
    })
}

/// A firearm's numbers (MODES.md 3.2) on an ability; its cooldown becomes the cycle.
#[allow(clippy::too_many_arguments)]
fn firearm(
    rate: TickRate,
    mut ability: Ability,
    magazine: u8,
    ammo: &str,
    reload_ms: u32,
    cycle_ms: u32,
    fire: FireMode,
    recoil: &[(f32, f32)],
    cone: [f32; 6],
    recover_ms: u32,
    scope: u8,
) -> Ability {
    ability.cooldown.ticks = rate.ms_to_ticks(cycle_ms);
    ability.firearm = Some(Firearm {
        magazine,
        ammo: ammo.to_string(),
        reload: rate.ms_to_ticks(reload_ms),
        cycle: rate.ms_to_ticks(cycle_ms),
        fire,
        headshot: 4.0,
        scope,
        recoil: recoil.to_vec(),
        cone: Cone {
            stand: cone[0],
            crouch: cone[1],
            scoped: cone[5],
            moving: cone[2],
            air: cone[3],
            shot: cone[4],
            recover: rate.ms_to_ticks(recover_ms),
        },
    });
    ability
}

fn projectile(
    rate: TickRate,
    speed: f32,
    gravity: f32,
    radius: f32,
    damage: DamagePacket,
    on_hit: Vec<Trigger>,
) -> Verb {
    Verb::Projectile(Projectile {
        speed,
        gravity_scale: gravity,
        radius,
        lifetime: rate.ms_to_ticks(3000),
        damage,
        pierce: 0,
        bounce: Bounce::default(),
        drag: 0.0,
        spawn: Origin::Weapon {
            offset: [16.0, 4.0, -2.0],
        },
        inherit_velocity: 0.0,
        spread_deg: 0.3,
        count: 1,
        on_hit,
        on_expire: vec![],
    })
}

#[allow(clippy::too_many_arguments)]
fn ability(
    id: u16,
    name: &str,
    cooldown_ms: u32,
    stamina: u16,
    focus: u16,
    move_scale: f32,
    interrupt: Interrupt,
    steps: Vec<(u32, Verb)>,
    rate: TickRate,
) -> Ability {
    Ability {
        id: AbilityId(id),
        name: name.into(),
        cost: Cost {
            stamina,
            focus,
            ..Cost::default()
        },
        cooldown: Cooldown {
            ticks: rate.ms_to_ticks(cooldown_ms),
            group: None,
        },
        steps: steps
            .into_iter()
            .map(|(ms, verb)| Step {
                at: rate.ms_to_ticks(ms),
                verb,
            })
            .collect(),
        move_scale,
        interrupt,
        chain: None,
        firearm: None,
        range: 0.0,
        heavy: false,
        ammo: String::new(),
    }
}

fn def(key: &str, slot: Slot, aspect: Option<Element>, ability: Ability) -> AbilityDef {
    AbilityDef {
        key: key.into(),
        ability,
        slot,
        aspect,
        squad: 0,
        creature: false,
        gun_melee: false,
    }
}

